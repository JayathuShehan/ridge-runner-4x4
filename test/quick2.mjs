import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 800, height: 450 } });
const errs = [];
p.on('pageerror', e => errs.push('PAGEERR ' + e.message));
p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ' ' + m.text().slice(0, 300)); });
const q = process.argv[2] || 'high';
await p.goto(`http://localhost:8765/dist/index.html?q=${q}&manual=1`);
await p.waitForFunction(() => window.__game, null, { timeout: 240000 });
const G = (f, a) => p.evaluate(f, a);
console.log(JSON.stringify(await G(() => ({ vegTris: window.__game.veg.tris, bush: window.__game.veg.bushTris }))));
await G(() => { const g = window.__game; g.start('trail'); g.S.countdown = 0; g.S.mode = 'play'; g.teleportCp(Number(new URLSearchParams(location.search).get('cp') || 0)); });
const cp = +(process.argv[3] || 0), secs = +(process.argv[4] || 2), name = process.argv[5] || 'q';
await G(([c, s]) => { const g = window.__game; g.teleportCp(c); g.S.next = c + 1; g.botDrive(s); }, [cp, secs]);
const t0 = Date.now();
const ms = await G(() => window.__game.renderOnce(0.05));
await G(() => window.__game.renderOnce(0.05));
console.log('render ms', ms.toFixed(0), 'wall', Date.now() - t0);
await p.screenshot({ path: `/tmp/v2-${name}.png`, timeout: 180000 });
console.log(errs.slice(0, 12).join('\n'));
await b.close();
